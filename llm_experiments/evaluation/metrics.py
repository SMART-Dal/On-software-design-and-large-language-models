class BinaryPromptEval:
    def __init__(self, ground_truth: List[Dict], answers: List[Dict]) -> None:
        """
        Initializes the evaluator, filters and aligns the data, and creates
        numerical lists for metric calculation.

        Args:
            ground_truth: A list of dictionaries, where each dict represents a
                          ground truth pair and its coupling status.
                          Example: {"pair": ["classX", "classY"], "coupled": True}
            answers: A list of dictionaries in the same format as ground_truth,
                     typically generated by an LLM.
        """
        # 1. Filter and normalize both the ground truth and answers lists.
        # This ensures we are working with clean, consistently formatted data.
        valid_ground_truth = ground_truth
        valid_answers = answers

        # 2. Create lookup maps for efficient comparison.
        # The keys are the sorted pairs (as tuples), and values are the boolean 'coupled' status.
        # Sorting the inner pair makes the key canonical (e.g., ("a", "b") is the same as ("b", "a")).
        sort_key = lambda x: x if x is not None else '' # For None values
        gt_map = {tuple(sorted(item['pair'], key=sort_key)): item['coupled'] for item in valid_ground_truth}
        answers_map = {tuple(sorted(item['pair'], key=sort_key)): item['coupled'] for item in valid_answers}

        # 3. Find the set of common pairs that exist in BOTH ground truth and answers.
        # This is the crucial step to ensure we only evaluate matching data.
        common_pairs = gt_map.keys() & answers_map.keys()
        
        # 4. Sort the common pairs to ensure a consistent, deterministic order.
        sorted_common_pairs = sorted(list(common_pairs))
        
        # Store the pairs that are being evaluated for transparency.
        self.evaluated_pairs = sorted_common_pairs

        # 5. Generate the final numerical lists (0s and 1s) based on the common, sorted pairs.
        # This guarantees that self.ground_truth_numerical[i] and self.answers_numerical[i]
        # correspond to the exact same pair.
        self.ground_truth_numerical = [int(gt_map[pair]) for pair in sorted_common_pairs]
        self.answers_numerical = [int(answers_map[pair]) for pair in sorted_common_pairs]

        # Final sanity check, which should always pass with this design.
        assert len(self.ground_truth_numerical) == len(self.answers_numerical)

    def calculate_f1_p_r(self):
        """
        Calculate precision, recall and f1-score
        """
        # Calculate precision, recall and f1-score
        precision = precision_score(self.ground_truth_numerical, self.answers_numerical, zero_division=0)
        recall = recall_score(self.ground_truth_numerical, self.answers_numerical, zero_division=0)
        f1 = f1_score(self.ground_truth_numerical, self.answers_numerical, zero_division=0)
        return {
            "precision": precision,
            "recall": recall,
            "f1": f1
        }
    
    def reset(self):
        """
        Reset the evaluation metrics
        """
        self.ground_truth = []
        self.answers = []
        self.ground_truth_numerical = []
        self.answers_numerical = []

class RetrievalPromptEval:
    """
    Class used to calculate F1, precision and recall for the retrieval-based task.
    """
    def __init__(self, ground_truth, answers) -> None:
        """
        Args:
            ground_truth: List of tuples of tightly coupled classes [(class1, dep1), (class1, dep2), ...].
            answers: List of tuples [(class1, dep1), (class1, dep2), ...] returned by the model.
        """
        # Normalize the pairs by sorting the classes in each pair. This is what frozenset does as a by product.
        # forzenset([foo, bar]) == forzenset([bar, foo]) is True. We use frozenset instead of set to make it hashable.
        # also lower case the classes to avoid case sensitivity issues.
        # Perform a first scan to ensure that the input is a list of tuples. Discard any elements that are not tuples.
        self.ground_truth = to_canonical_set(ground_truth)
        self.answers = to_canonical_set(answers)

    def calculate_f1_p_r(self):
        """
        Calculate precision, recall and f1-score
        """
        tp = self.ground_truth.intersection(self.answers)
        fp = self.answers - self.ground_truth
        fn = self.ground_truth - self.answers

        tp_count = len(tp)
        fp_count = len(fp)
        fn_count = len(fn)

        precision = tp_count / (tp_count + fp_count) if (tp_count + fp_count) > 0 else 0
        recall = tp_count / (tp_count + fn_count) if (tp_count + fn_count) > 0 else 0
        f1 = 2 * (precision * recall) / (precision + recall) if (precision + recall) > 0 else 0

        return {
            "precision": precision,
            "recall": recall,
            "f1": f1
        }
    
    def get_unretrieved_ground_truth(self):
        """
        Get the ground truth pairs that were not retrieved by the model.
        """
        return self.ground_truth - self.answers
    
    def reset(self):
        """
        Reset the evaluation metrics
        """
        self.ground_truth = set()
        self.answers = set()
         
def calculate_jaccard_for_pairs(list_a, list_b):
    """
    Calculates the Jaccard Similarity between two lists of pairs,
    where the position of elements in a pair does not matter.

    Args:
        list_a: The first list of tuples.
        list_b: The second list of tuples.

    Returns:
        The Jaccard Similarity score as a float between 0.0 and 1.0.
    """
    # Convert both lists to sets of canonical pairs
    set_a = to_canonical_set(list_a)
    set_b = to_canonical_set(list_b)

    # Calculate the size of the intersection and union
    intersection_size = len(set_a.intersection(set_b))
    union_size = len(set_a.union(set_b))

    # Calculate Jaccard Similarity
    if union_size == 0:
        # If both lists are empty, they are perfectly similar.
        return 1.0
    else:
        return intersection_size / union_size